using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Raven.Client.Documents;
using Raven.Client.Documents.Indexes;
using Raven.Client.Documents.Queries.Timings;
using Raven.Server.Documents.Queries;
using Tests.Infrastructure;
using Xunit;
using static FastTests.Corax.JoinTestHelpers;

namespace FastTests.Corax;

// Opt-in: RAVEN_JOIN_BIGSUB=&lt;outer entries&gt, RAVEN_JOIN_BIGSUB_ENCODED=off to decode and encode the ids of the join
public class JoinBigSubBenchmark(ITestOutputHelper output) : RavenTestBase(output)
{
    private class Message { public string ContextDocumentId; public string Text; }
    private class Context { public bool IsActive; public bool Third; public string Name; }

    private class MessageIndex : AbstractIndexCreationTask<Message>
    {
        public MessageIndex()
        {
            Map = ms => from m in ms select new { m.ContextDocumentId, m.Text };
            Index(x => x.ContextDocumentId, FieldIndexing.Key);
        }

        public override string IndexName => "ConversationMessageListIndex";
    }

    private class ContextIndex : AbstractIndexCreationTask<Context>
    {
        public ContextIndex() => Map = cs => from c in cs select new { c.IsActive, c.Third, c.Name };
        public override string IndexName => "SearchIndex";
    }

    // the ids of the contexts look like the ones a client makes
    internal static string ContextId(int c)
    {
        if (Environment.GetEnvironmentVariable("RAVEN_JOIN_BIGSUB_IDS") == "short")
            return $"ConversationContexts/{c}-A";

        var h = (uint)c * 2654435761u;
        return $"ConversationContexts/{new Guid((int)h, (short)(h >> 7), (short)(h >> 3), (byte)c, (byte)(c >> 8), (byte)(c >> 16), 4, 5, 6, 7, 8)}";
    }

    // Number of outer entries that reference a joined id, as generated by ReferencedContext
    internal static int ReferencedContext(int message, int contexts) => message % 100 < 36 ? (int)((message * 7919L) % contexts) : -1;

    [JoinBenchmarkFact("RAVEN_JOIN_BIGSUB", RavenTestCategory.Corax | RavenTestCategory.Querying)]
    public void Run()
    {
        var messages = int.Parse(Environment.GetEnvironmentVariable("RAVEN_JOIN_BIGSUB"));
        var contexts = int.Parse(Environment.GetEnvironmentVariable("RAVEN_JOIN_BIGSUB_CONTEXTS") ?? "223524");
        var reps = int.Parse(Environment.GetEnvironmentVariable("RAVEN_JOIN_BIGSUB_REPS") ?? "9");

        JoinEncodedKeys.Enabled = Environment.GetEnvironmentVariable("RAVEN_JOIN_BIGSUB_ENCODED") != "off";

        using var store = GetDocumentStore(Options.ForSearchEngine(RavenSearchEngineMode.Corax));
        new MessageIndex().Execute(store);
        new ContextIndex().Execute(store);
        using (var bulk = store.BulkInsert())
        {
            for (var c = 0; c < contexts; c++)
                bulk.Store(new Context { IsActive = true, Third = c % 3 == 0, Name = c % 10 == 0 ? "tenth" : "other" }, ContextId(c));
            for (var m = 0; m < messages; m++)
            {
                var c = ReferencedContext(m, contexts);
                bulk.Store(new Message { ContextDocumentId = c >= 0 ? ContextId(c) : $"other/{m % 5000}", Text = "t" }, $"messages/{m}");
            }
        }

        Indexes.WaitForIndexing(store, timeout: TimeSpan.FromMinutes(30));

        long expectedAll = 0, expectedTenth = 0, expectedThird = 0;
        for (var m = 0; m < messages; m++)
        {
            var c = ReferencedContext(m, contexts);
            if (c < 0)
                continue;
            expectedAll++;
            if (c % 10 == 0)
                expectedTenth++;
            if (c % 3 == 0)
                expectedThird++;
        }

        var report = new StringBuilder();
        report.AppendLine($"=== {messages} messages, {contexts} contexts, {reps} reps ({DateTime.Now:yyyy-MM-dd HH:mm}), load {Environment.GetEnvironmentVariable("RAVEN_JOIN_BIGSUB_LOAD")} ===");
        const string outer = "from index 'ConversationMessageListIndex' as m ";
        Measure(report, store, "plain (no join)", $"{outer} select id() limit 0, 5", messages, reps);
        Measure(report, store, "join, sub-query matches all", $"{outer} join (from index 'SearchIndex' where IsActive = true) as c on m.ContextDocumentId = id(c) select id() limit 0, 5", expectedAll, reps);
        Measure(report, store, "join, sub-query matches 33%", $"{outer} join (from index 'SearchIndex' where Third = true) as c on m.ContextDocumentId = id(c) select id() limit 0, 5", expectedThird, reps);
        Measure(report, store, "join, sub-query matches 10%", $"{outer} join (from index 'SearchIndex' where Name = 'tenth') as c on m.ContextDocumentId = id(c) select id() limit 0, 5", expectedTenth, reps);
        output.WriteLine(report.ToString());
        AppendReport("RAVEN_JOIN_BIGSUB_OUT", "join-bigsub.txt", report);
    }

    private static void Measure(StringBuilder report, IDocumentStore store, string arm, string rql, long expectedTotal, int reps)
    {
        var durations = new List<double>();
        QueryTimings last = null;
        for (var i = 0; i < 2 + reps; i++)
        {
            using var session = store.OpenSession();
            session.Advanced.RawQuery<object>(rql).NoCaching().Statistics(out var stats).ToList();
            Assert.Equal(expectedTotal, stats.TotalResults);
            if (i >= 2)
                durations.Add(stats.DurationInMs);
        }

        using (var session = store.OpenSession())
        {
            session.Advanced.RawQuery<object>(rql + " include timings()").NoCaching().Timings(out last).ToList();
        }

        report.AppendLine($"--- {arm}: server ms median {Median(durations):F0} (min {durations.Min():F0}, max {durations.Max():F0})");
        Dump(report, last, "    ");
    }

    private static void Dump(StringBuilder report, QueryTimings timings, string indent)
    {
        if (timings.Timings == null && timings.Counters == null)
            return;
        if (timings.Counters != null)
            foreach (var c in timings.Counters)
                report.AppendLine($"{indent}[{c.Key}] = {c.Value:N0}");
        if (timings.Timings == null)
            return;
        foreach (var (name, child) in timings.Timings)
        {
            report.AppendLine($"{indent}{name}: {child.DurationInMs} ms");
            Dump(report, child, indent + "  ");
        }
    }
}
